/**
 * In-memory PostgREST emulator for the tables the consent flow touches.
 *
 * Supported query shapes (as produced by lib/supabase.ts):
 *   GET  /rest/v1/{table}?user_id=eq.X[&withdrawn_at=is.null]&order=created_at.desc&limit=1&select=...
 *   POST /rest/v1/consent_records      (insert; return=minimal)
 *   POST /rest/v1/user_profiles         (merge-duplicates upsert by user_id)
 *   PATCH /rest/v1/consent_records?id=eq.Y
 * And /auth/v1/user (requireUser path).
 *
 * Rows are plain objects; `id` and `created_at` are generated by the emulator.
 */
class Emulator {
  rows: Array<Record<string, unknown>> = [];
  profiles: Array<Record<string, unknown>> = [];
  authOk = true;
  failInsert = false;
  failInsertUnique = false;
  hideActiveOnFirstSelect = false;
  failPatch = false;
  failSelect = false;
  private seq = 0;

  private nextId(prefix: string): string {
    this.seq += 1;
    return `${prefix}-test-${String(this.seq).padStart(4, "0")}`;
  }

  private rowsFor(table: string, url: URL): Array<Record<string, unknown>> {
    const params = url.searchParams;
    let rows =
      table === "consent_records" ? this.rows : this.profiles;
    // One-shot race simulation: the first active-row read must not see the
    // (concurrent) winner row, as it would have been read before it landed.
    if (
      this.hideActiveOnFirstSelect &&
      table === "consent_records" &&
      params.get("withdrawn_at") === "is.null"
    ) {
      this.hideActiveOnFirstSelect = false;
      return [];
    }
    for (const [key, value] of params.entries()) {
      if (key === "user_id") {
        const m = value.match(/^eq\.(.*)$/);
        if (m) rows = rows.filter((r) => r.user_id === m[1]);
      } else if (key === "withdrawn_at") {
        const m = value.match(/^is\.(.*)$/);
        if (m && m[1] === "null") rows = rows.filter((r) => r.withdrawn_at == null);
      } else if (key === "id") {
        const m = value.match(/^eq\.(.*)$/);
        if (m) rows = rows.filter((r) => r.id === m[1]);
      }
    }
    // order=created_at.desc
    const order = params.get("order");
    if (order && order.includes("desc")) {
      rows = [...rows].sort((a, b) => String(b.created_at).localeCompare(String(a.created_at)));
    }
    const limit = Number(params.get("limit") ?? "0");
    if (limit > 0) rows = rows.slice(0, limit);
    return rows;
  }

  readonly baseUrl = "https://fake.supabase.test";

  private json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), {
      status,
      headers: { "Content-Type": "application/json" },
    });
  }

  private async handleAuthUser(): Promise<Response> {
    if (!this.authOk) {
      return this.json({ error: "invalid_jwt", message: "invalid or expired token" }, 401);
    }
    return this.json({
      id: "user-1",
      email: "user@example.com",
      user_metadata: { name: "Test User", provider: "google" },
      app_metadata: {},
    });
  }

  handle = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    const url = new URL(typeof input === "string" ? input : input instanceof URL ? input.toString() : input.url);
    const path = url.pathname;
    const method = (init?.method ?? "GET").toUpperCase();

    if (path === "/auth/v1/user") {
      return this.handleAuthUser();
    }

    const restMatch = path.match(/^\/rest\/v1\/(user_profiles|consent_records)$/);
    if (restMatch) {
      const table = restMatch[1];
      if (method === "GET") {
        if (this.failSelect) {
          return this.json({ code: "42P01", message: `relation public.${table} does not exist` }, 404);
        }
        return this.json(this.rowsFor(table, url));
      }
      if (method === "POST") {
        const rows = JSON.parse((init?.body as string) ?? "[]") as Array<Record<string, unknown>>;
        if (this.failInsert) {
          return this.json({ code: "42P01", message: `relation public.${table} does not exist` }, 404);
        }
        if (this.failInsertUnique && table === "consent_records") {
          return this.json({ code: "23505", message: 'duplicate key value violates unique constraint "consent_records_active_user_id"' }, 409);
        }
        if (table === "consent_records") {
          const inserted = rows.map((r) => ({
            id: this.nextId("cr"),
            created_at: new Date().toISOString(),
            withdrawn_at: null,
            ...r,
          }));
          this.rows.push(...inserted);
          return this.json({}, 201);
        }
        // user_profiles upsert merge-duplicates by user_id
        for (const r of rows) {
          const userId = String(r.user_id ?? "");
          const existing = this.profiles.find((p) => p.user_id === userId);
          if (existing) {
            Object.assign(existing, r);
          } else {
            this.profiles.push({
              id: this.nextId("prof"),
              user_id: userId,
              created_at: new Date().toISOString(),
              ...r,
            });
          }
        }
        return this.json({}, 201);
      }
      if (method === "PATCH") {
        if (this.failPatch) {
          return this.json({ code: "42P01", message: `relation public.${table} does not exist` }, 404);
        }
        const patch = JSON.parse((init?.body as string) ?? "{}") as Record<string, unknown>;
        const ids = this.rowsFor(table, url);
        for (const row of ids) Object.assign(row, patch);
        return new Response(null, { status: 204 });
      }
    }

    return this.json({ error: "unhandled", path }, 404);
  };

  /** Extract active (non-withdrawn) rows for the user. */
  activeFor(userId: string): Array<Record<string, unknown>> {
    return this.rows
      .filter((r) => r.user_id === userId && r.withdrawn_at == null)
      .sort((a, b) => String(b.created_at).localeCompare(String(a.created_at)));
  }

  allFor(userId: string): Array<Record<string, unknown>> {
    return this.rows.filter((r) => r.user_id === userId);
  }

  profileFor(userId: string): Record<string, unknown> | undefined {
    return this.profiles.find((p) => p.user_id === userId);
  }
}

function installStubs(emul: Emulator): () => void {
  const prev = {
    fetch: globalThis.fetch,
    url: process.env.NEXT_PUBLIC_SUPABASE_URL,
    key: process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
  };
  process.env.NEXT_PUBLIC_SUPABASE_URL = emul.baseUrl;
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY = "anon-test-key";
  process.env.SUPABASE_URL = emul.baseUrl;
  process.env.SUPABASE_SERVICE_ROLE_KEY = "service-role-test-key";
  globalThis.fetch = emul.handle as typeof fetch;
  return () => {
    globalThis.fetch = prev.fetch;
    if (prev.url === undefined) delete process.env.NEXT_PUBLIC_SUPABASE_URL;
    else process.env.NEXT_PUBLIC_SUPABASE_URL = prev.url;
    if (prev.key === undefined) delete process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
    else process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY = prev.key;
    delete process.env.SUPABASE_SERVICE_ROLE_KEY;
  };
}

